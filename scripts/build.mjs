import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const source = readFileSync(new URL("../style.css", import.meta.url), "utf8");
const start = "/* Slidebox component: begin */";
const end = "/* Slidebox component: end */";
const beginAt = source.indexOf(start);
const endAt = source.indexOf(end);
if (beginAt < 0 || endAt <= beginAt) {
  throw new Error("Slidebox component markers are missing from style.css");
}
let css = source.slice(beginAt + start.length, endAt).trim() + "\n";
if (!css.includes(".slidebox:checked::after")) {
  throw new Error("Extracted CSS is missing checked-state styling");
}
const controls = {
  width: "--_container-width-ratio", spacing: "--_thumb-spacing-ratio",
  deform: "--_deform", duration: "--_duration", easing: "--_easing-function",
  track: "--_track", border: "--_border", off: "--_off", on: "--_on", size: "font-size",
};
const root = postcss.parse(css);
const base = root.nodes.find(node => node.selector === ".slidebox");
for (const declaration of base.nodes) {
  const control = Object.keys(controls).find(key => controls[key] === declaration.prop);
  if (control) {
    const fallback = control === "on" ? `var(--_accent, ${declaration.value})` : declaration.value;
    declaration.value = `var(--slidebox-${control}, ${fallback})`;
  }
}
root.walkAtRules("supports", rule => {
  rule.walkDecls("--_on", declaration => { declaration.prop = "--_accent"; });
});
css = root.toString();
const nested = root.clone();
nested.walkRules(rule => { rule.selector = rule.selector.replaceAll(".slidebox", "&"); });
const indent = text => text.split("\n").map(line => "  " + line).join("\n");
const sass = `// Generated by scripts/build.mjs.\n@use "sass:map";\n\n$defaults: () !default;\n\n@mixin slidebox($options: ()) {\n  @each $name, $value in map.merge($defaults, $options) {\n    --slidebox-#{$name}: #{$value};\n  }\n${indent(nested.toString())}}\n`;
const lessNested = nested.clone();
lessNested.walkDecls(declaration => {
  // Let the browser evaluate CSS math involving custom properties, not Less.
  if (/\b(?:max|min|clamp)\(/.test(declaration.value)) declaration.value = `~"${declaration.value}"`;
});
const less = `// Generated by scripts/build.mjs.\n.slidebox-option(@name; @value) when not (@value = false) {\n  --slidebox-@{name}: @value;\n}\n.slidebox(${Object.keys(controls).map(key => `@${key}: false`).join("; ")}) {\n${Object.keys(controls).map(key => `  .slidebox-option(${key}; @${key});`).join("\n")}\n${indent(lessNested.toString())}}\n`;
function rulesFor(container) {
  const result = {};
  for (const node of container.nodes) {
    if (node.type === "decl") result[node.prop] = node.value;
    else if (node.type === "rule") result[node.selector.replaceAll(".slidebox", "&")] = rulesFor(node);
    else if (node.type === "atrule") result[`@${node.name} ${node.params}`] = rulesFor(node);
  }
  return result;
}
const rules = rulesFor(root);
const utility = { ...rules["&"] };
for (const [key, value] of Object.entries(rules)) {
  if (key !== "&") utility[key] = value;
}
const outputs = {
  "dist/css/slidebox.css": css,
  "scss/slidebox.scss": '@use "mixins";\n.slidebox { @include mixins.slidebox(); }\n',
  "scss/_mixins.scss": sass,
  "less/slidebox.less": less,
  "tailwind/rules.json": JSON.stringify(utility, null, 2) + "\n",
};
for (const [output, content] of Object.entries(outputs)) {
  mkdirSync(new URL("../" + output.substring(0, output.lastIndexOf("/")), import.meta.url), { recursive: true });
  writeFileSync(new URL("../" + output, import.meta.url), content);
}
console.log("Built CSS, Sass, Less, and Tailwind entrypoints");
